def main() -> int:
    if not TARGET.exists():
        print(f"zork_agent_patch: target missing {TARGET}", file=sys.stderr)
        return 1
    src = TARGET.read_text(encoding="utf-8")
    if MARKER in src:
        print("zork_agent_patch: already applied (K49)")
        return 0
    # K27 — strip any prior K17/K19/K23 injection so we can re-inject with
    # the relaxed verb-whitelist body.
    import re as _re
    for old in OLD_MARKERS:
        if old in src:
            pattern = _re.compile(
                _re.escape("            " + old + "\n")
                + r".*?^\n",
                _re.DOTALL | _re.MULTILINE,
            )
            new_src = pattern.sub("", src, count=1)
            if old in new_src:
                print(f"zork_agent_patch: failed to strip old marker {old!r}", file=sys.stderr)
                return 3
            src = new_src
    if ANCHOR not in src:
        print("zork_agent_patch: anchor not found", file=sys.stderr)
        return 2
    new = src.replace(ANCHOR, INJECTION + ANCHOR, 1)
    TARGET.write_text(new, encoding="utf-8")
