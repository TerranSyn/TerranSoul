#!/usr/bin/env node
// benchmark/scripts/zork-bench/setup.mjs
//
// One-time setup for the ZorkGPT × TerranSoul brain bench.
//   1. Clone stickystyle/ZorkGPT at a pinned commit into
//      target-copilot-bench/zorkgpt-src/ (gitignored).
//   2. uv sync inside the clone.
//   3. Drop the bench-specific .env that points the LM stack at
//      local Ollama and disables Langfuse.
//   4. Probe TerranSoul MCP health and refuse to continue if degraded.
//
// See benchmark/terransoul/zorkgpt/README.md for the full design.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import http from 'node:http';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..', '..', '..');

// Pinned ZorkGPT commit — README pin in setup.mjs is the source of truth.
// 4c80f40 is the "use configured paths for game files" commit (Apr 2026, last on main).
const ZORKGPT_PIN = '4c80f401a17b5f25b3c183d35ac171bf20268864';
const ZORKGPT_DIR = resolve(REPO_ROOT, 'target-copilot-bench', 'zorkgpt-src');

const ENV_CONTENT = `# Auto-generated by benchmark/scripts/zork-bench/setup.mjs
# Points ZorkGPT's OpenAI-compatible LLM client at local Ollama.
CLIENT_BASE_URL=http://localhost:11434/v1
CLIENT_API_KEY=ollama
ZORKGPT_CLIENT_API_KEY=ollama

AGENT_MODEL=gemma4:e4b
CRITIC_MODEL=gemma4:e4b
INFO_EXT_MODEL=gemma4:e4b
ANALYSIS_MODEL=gemma4:e4b

MAX_TURNS_PER_EPISODE=300

# Langfuse disabled — bench writes its own JSONL trace.
LANGFUSE_PUBLIC_KEY=
LANGFUSE_SECRET_KEY=
`;

function run(cmd, args, opts = {}) {
  console.log(`$ ${cmd} ${args.join(' ')}`);
  const r = spawnSync(cmd, args, { stdio: 'inherit', shell: false, ...opts });
  if (r.status !== 0) {
    console.error(`✗ command failed (exit ${r.status}): ${cmd} ${args.join(' ')}`);
    process.exit(r.status ?? 1);
  }
}

function probeMcp() {
  return new Promise((resolveP) => {
    const ports = [7421, 7423, 7422];
    let i = 0;
    const tryPort = () => {
      if (i >= ports.length) return resolveP(null);
      const port = ports[i++];
      const req = http.get(
        { host: '127.0.0.1', port, path: '/health', timeout: 800 },
        (res) => {
          let body = '';
          res.on('data', (c) => (body += c));
          res.on('end', () => {
            if (res.statusCode === 200) resolveP({ port, body });
            else tryPort();
          });
        },
      );
      req.on('error', tryPort);
      req.on('timeout', () => {
        req.destroy();
        tryPort();
      });
    };
    tryPort();
  });
}

async function main() {
  console.log('=== ZorkGPT × TerranSoul brain bench — setup ===');

  // 1. Check prereqs.
  if (spawnSync('git', ['--version'], { stdio: 'ignore' }).status !== 0) {
    console.error('✗ git not on PATH');
    process.exit(1);
  }
  if (spawnSync('uv', ['--version'], { stdio: 'ignore' }).status !== 0) {
    console.error('✗ uv not on PATH. Install: irm https://astral.sh/uv/install.ps1 | iex');
    process.exit(1);
  }

  // 2. Probe MCP. Hard-block bench setup if degraded.
  console.log('→ probing TerranSoul MCP /health …');
  const mcp = await probeMcp();
  if (!mcp) {
    console.error('✗ no TerranSoul MCP found on :7421, :7423, or :7422.');
    console.error('  Start it with: node scripts/copilot-start-mcp.mjs');
    process.exit(1);
  }
  console.log(`✓ MCP reachable on port ${mcp.port}`);

  // 3. Clone ZorkGPT at the pinned commit (idempotent — skip if already cloned).
  if (!existsSync(ZORKGPT_DIR)) {
    mkdirSync(dirname(ZORKGPT_DIR), { recursive: true });
    run('git', ['clone', '--no-checkout', 'https://github.com/stickystyle/ZorkGPT', ZORKGPT_DIR]);
  }
  run('git', ['-C', ZORKGPT_DIR, 'fetch', '--depth=1', 'origin', ZORKGPT_PIN]);
  run('git', ['-C', ZORKGPT_DIR, 'checkout', ZORKGPT_PIN]);
  console.log(`✓ ZorkGPT checked out at ${ZORKGPT_PIN.slice(0, 7)}`);

  // 4. uv sync.
  run('uv', ['sync'], { cwd: ZORKGPT_DIR });
  console.log('✓ uv sync complete');

  // 5. Write the bench .env (clobbers any prior).
  writeFileSync(resolve(ZORKGPT_DIR, '.env'), ENV_CONTENT, 'utf8');
  console.log('✓ wrote .env pointing at local Ollama (gemma3:4b)');

  // 6. Copy the bridge + runner into the ZorkGPT clone so `uv run python` picks them up.
  const bridgeSrc = resolve(__dirname, 'terransoul_brain_bridge.py');
  const runSrc = resolve(__dirname, 'run_bench.py');
  if (!existsSync(bridgeSrc) || !existsSync(runSrc)) {
    console.error('✗ bridge or runner missing — re-run from a clean repo checkout');
    process.exit(1);
  }
  copyFileSync(bridgeSrc, resolve(ZORKGPT_DIR, 'terransoul_brain_bridge.py'));
  copyFileSync(runSrc, resolve(ZORKGPT_DIR, 'run_bench.py'));
  console.log('✓ copied bridge + runner into ZorkGPT clone');

  // 7. Ensure bench output dir exists.
  const outDir = resolve(REPO_ROOT, 'target-copilot-bench', 'bench-results');
  mkdirSync(outDir, { recursive: true });

  console.log('\n=== Setup complete ===');
  console.log('Next: node benchmark/scripts/zork-bench/run.mjs --arm all --episodes 3');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
